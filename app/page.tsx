interface PartLike extends Partial<ToolPartLike> {
  type: string;
  text?: string;
  url?: string;
  mediaType?: string;
}

interface Attachment {
  dataUrl: string;
  mediaType: string;
  bytes: number;
}

interface LocalNotice {
  id: string;
  text: string;
}

type DrawerNotice = { type: 'ok' | 'error'; text: string } | null;

const PERMISSIONS_KEY = 'prefs/permissions';
const PERSONA_KEY = 'prefs/persona';
const THREAD_INDEX_KEY = 'threads/index';

function textOf(message: UIMessage): string {
  return (message.parts as unknown as PartLike[])
    .filter((p) => p.type === 'text')
    .map((p) => p.text ?? '')
    .join(' ');
}

function friendlyError(message: string): string {
  try {
    const parsed = JSON.parse(message) as { message?: string };
    if (parsed.message) return parsed.message;
  } catch {
    /* not JSON */
  }
  return message;
}

function CodeChunk({ raw }: { raw: string }) {
  const newline = raw.indexOf('\n');
  const lang = newline > -1 ? raw.slice(0, newline).trim() : '';
  const code = newline > -1 ? raw.slice(newline + 1) : raw;
  return (
    <div className='relative rounded-xl bg-black/45'>
      {lang && <span className='absolute left-3 top-1.5 text-[10px] text-[color:var(--muted)]'>{lang}</span>}
      <button type='button' className='ghost-btn absolute right-2 top-2 rounded-lg p-1.5' onClick={() => void navigator.clipboard?.writeText(code)} aria-label='Copy code'>
        <Icon name='copy' size={12} />
      </button>
      <pre className='code scroll-thin max-h-96 p-3 pt-6'>{code}</pre>
    </div>
  );
}

function RichText({ text }: { text: string }) {
  const chunks = text.split('```');
  return (
    <div className='space-y-2 text-sm leading-relaxed'>
      {chunks.map((c, i) =>
        i % 2 === 1 ? <CodeChunk key={i} raw={c} /> : c.trim() ? <p key={i} className='whitespace-pre-wrap break-words'>{c.trim()}</p> : null,
      )}
    </div>
  );
}

function workspacesOf(tools: ToolPartLike[]): { id: string; title: string; files: WorkspaceFile[]; note?: string }[] {
  const out: { id: string; title: string; files: WorkspaceFile[]; note?: string }[] = [];
  for (const t of tools) {
    const name = toolNameOf(t);
    if (t.state !== 'output-available' || (name !== 'renderMultiFileWorkspace' && name !== 'delegateToCoderWorker')) continue;
    const o = t.output as { files?: unknown; title?: unknown; notes?: unknown; node?: unknown } | undefined;
    if (!o || !Array.isArray(o.files)) continue;
    const files = (o.files as { path?: unknown; content?: unknown }[])
      .filter((f) => typeof f.path === 'string' && typeof f.content === 'string')
      .map((f) => ({ path: f.path as string, content: f.content as string }));
    if (files.length === 0) continue;
    const noteParts = [typeof o.notes === 'string' ? o.notes : '', typeof o.node === 'string' ? 'Generated by ' + o.node : ''].filter(Boolean);
    out.push({ id: t.toolCallId, title: typeof o.title === 'string' ? o.title : 'Generated files', files, note: noteParts.join(' - ') || undefined });
  }
  return out;
}

function MessageView({ message, onDecision }: { message: UIMessage; onDecision: (id: string, approved: boolean) => void }) {
  const parts = message.parts as unknown as PartLike[];
  const tools = parts.filter((p) => p.type.startsWith('tool-')) as unknown as ToolPartLike[];
  const pending = tools.filter((t) => t.state === 'approval-requested' && t.approval);
  const spaces = workspacesOf(tools);
  const isUser = message.role === 'user';
  return (
    <div className={'flex ' + (isUser ? 'justify-end' : 'justify-start')}>
      <div className={'max-w-[92%] space-y-2 ' + (isUser ? 'glass rounded-2xl px-4 py-3' : 'w-full')} style={isUser ? { borderColor: 'rgba(139,108,255,0.35)' } : undefined}>
        {parts.map((p, i) =>
          p.type === 'file' && p.url && (p.mediaType ?? '').startsWith('image/') ? (
            // eslint-disable-next-line @next/next/no-img-element
            <img key={i} src={p.url} alt='Attached screenshot' className='max-h-56 rounded-lg' />
          ) : null,
        )}
        {!isUser && <AgentTraceAccordion parts={tools} />}
        {pending.map((t) => (
          <ApprovalCard key={t.toolCallId} part={t} onDecision={onDecision} />
        ))}
        {spaces.map((w) => (
          <MultiFileWorkspace key={w.id} title={w.title} files={w.files} note={w.note} />
        ))}
        {parts.filter((p) => p.type === 'text' && (p.text ?? '').trim()).map((p, i) => (
          <RichText key={i} text={p.text ?? ''} />
        ))}
      </div>
    </div>
  );
}

export default function Home() {
  const [authed, setAuthed] = useState<boolean | null>(null);
  const [password, setPassword] = useState('');
  const [loginError, setLoginError] = useState('');
  const [loggingIn, setLoggingIn] = useState(false);

  const [threadId, setThreadId] = useState<string>('');
  const [threads, setThreads] = useState<ThreadMeta[]>([]);
  const [persona, setPersona] = useState<Persona>('default');
  const [permissions, setPermissions] = useState<Record<string, Permission>>({});
  const [facts, setFacts] = useState<MemoryFact[]>([]);
  const [connectorsOpen, setConnectorsOpen] = useState(false);
  const [drawerNotice, setDrawerNotice] = useState<DrawerNotice>(null);
  const [sidebarOpen, setSidebarOpen] = useState(false);
  const [input, setInput] = useState('');
  const [attachment, setAttachment] = useState<Attachment | null>(null);
  const [attachError, setAttachError] = useState('');
  const [notices, setNotices] = useState<LocalNotice[]>([]);
  const [nodeLabel, setNodeLabel] = useState('');

  const stateRef = useRef({ permissions, persona, facts, nodeIndex: 0 });
  stateRef.current.permissions = permissions;
  stateRef.current.persona = persona;
  stateRef.current.facts = facts;
  const fileInput = useRef<HTMLInputElement>(null);
  const bottomRef = useRef<HTMLDivElement>(null);
  const capturedMemory = useRef<Set<string>>(new Set());

  const transport = useMemo(
    () =>
      new DefaultChatTransport({
        api: '/api/chat',
        body: () => ({
          permissions: stateRef.current.permissions,
          persona: stateRef.current.persona,
          memory: factsForPrompt(stateRef.current.facts, 10),
          nodeIndex: stateRef.current.nodeIndex,
        }),
        fetch: async (url, init) => {
          const res = await fetch(url, init);
          const node = res.headers.get('x-agent-node');
          if (node) setNodeLabel(node);
          if (res.status === 401) setAuthed(false);
          return res;
        },
      }),
    [],
  );

  const { messages, setMessages, sendMessage, status, error, stop, regenerate, addToolApprovalResponse, clearError } = useChat({
    id: 'main',
    transport,
    sendAutomaticallyWhen: lastAssistantMessageIsCompleteWithApprovalResponses,
  });

  const busy = status === 'submitted' || status === 'streaming';

  const pushNotice = useCallback((text: string) => {
    setNotices((n) => [...n, { id: crypto.randomUUID(), text }].slice(-4));
  }, []);

  /* ---------- auth ---------- */
  useEffect(() => {
    void apiRequest<{ authed?: boolean }>('/api/auth').then((r) => setAuthed(Boolean(r.data?.authed)));
    const params = new URLSearchParams(window.location.search);
    if (params.get('connector')) {
      setDrawerNotice({ type: params.get('status') === 'ok' ? 'ok' : 'error', text: params.get('msg') ?? 'Connector update finished.' });
      setConnectorsOpen(true);
      window.history.replaceState(null, '', '/');
    }
  }, []);

  async function login(): Promise<void> {
    setLoggingIn(true);
    setLoginError('');
    const r = await apiRequest<{ authed?: boolean }>('/api/auth', { method: 'POST', body: { password } });
    setLoggingIn(false);
    if (r.ok) {
      setPassword('');
      setAuthed(true);
    } else {
      setLoginError(r.message);
    }
  }

  async function logout(): Promise<void> {
    await apiRequest('/api/auth', { method: 'DELETE' });
    setAuthed(false);
    setMessages([]);
  }

  /* ---------- bootstrap after login ---------- */
  const openThread = useCallback(
    async (id: string) => {
      stop();
      const r = await storage.load<{ messages: UIMessage[] }>('threads/' + id);
      setThreadId(id);
      setMessages(r.value?.messages ?? []);
      setSidebarOpen(false);
    },
    [setMessages, stop],
  );

  useEffect(() => {
    if (authed !== true) return;
    const stopMonitor = storage.startHealthMonitor();
    void (async () => {
      const perms = await storage.load<Record<string, Permission>>(PERMISSIONS_KEY);
      if (perms.value && typeof perms.value === 'object') setPermissions(perms.value);
      const p = await storage.load<string>(PERSONA_KEY);
      setPersona(normalizePersona(p.value));
      setFacts(await loadFacts());
      const idx = await storage.load<ThreadMeta[]>(THREAD_INDEX_KEY);
      const list = Array.isArray(idx.value) ? idx.value : [];
      setThreads(list);
      if (list.length > 0) await openThread(list[0].id);
      else setThreadId(crypto.randomUUID());
    })();
    return () => stopMonitor();
    // eslint-disable-next-line react-hooks/exhaustive-deps
  }, [authed]);

  /* ---------- persist thread ---------- */
  useEffect(() => {
    if (authed !== true || !threadId || messages.length === 0 || busy) return;
    const timer = window.setTimeout(() => {
      void (async () => {
        const firstUser = messages.find((m) => m.role === 'user');
        const title = (firstUser ? textOf(firstUser) : 'New chat').slice(0, 60) || 'New chat';
        const slim = messages.map((m) => ({
          ...m,
          parts: (m.parts as unknown as PartLike[]).map((p) => (p.type === 'file' ? { type: 'text', text: '[image attached]' } : p)),
        }));
        await storage.save('threads/' + threadId, { id: threadId, title, messages: slim });
        const idx = await storage.load<ThreadMeta[]>(THREAD_INDEX_KEY);
        const rest = (Array.isArray(idx.value) ? idx.value : []).filter((t) => t.id !== threadId);
        const next = [{ id: threadId, title, updatedAt: Date.now() }, ...rest].slice(0, 50);
        await storage.save(THREAD_INDEX_KEY, next);
        setThreads(next);
      })();
    }, 800);
    return () => window.clearTimeout(timer);
  }, [messages, busy, authed, threadId]);

  /* ---------- capture memory saved by the agent ---------- */
  useEffect(() => {
    for (const m of messages) {
      for (const part of m.parts as unknown as PartLike[]) {
        if (part.type !== 'tool-saveMemoryFact' || part.state !== 'output-available' || !part.toolCallId) continue;
        if (capturedMemory.current.has(part.toolCallId)) continue;
        capturedMemory.current.add(part.toolCallId);
        const out = part.output as { saved?: boolean; id?: string; fact?: string; tag?: string; ts?: number } | undefined;
        if (out?.saved && typeof out.fact === 'string') void addFact({ id: out.id, fact: out.fact, tag: out.tag, ts: out.ts }).then(setFacts);
      }
    }
  }, [messages]);

  useEffect(() => {
    bottomRef.current?.scrollIntoView({ behavior: 'smooth', block: 'end' });
  }, [messages, notices, status]);

  /* ---------- actions ---------- */
  function updatePermissions(next: Record<string, Permission>): void {
    setPermissions(next);
    void storage.save(PERMISSIONS_KEY, next);
  }

  function updatePersona(next: Persona): void {
    setPersona(next);
    void storage.save(PERSONA_KEY, next);
  }

  function newThread(): void {
    stop();
    setMessages([]);
    setThreadId(crypto.randomUUID());
    setNotices([]);
    setSidebarOpen(false);
  }

  async function removeThread(id: string): Promise<void> {
    await storage.remove('threads/' + id);
    const next = threads.filter((t) => t.id !== id);
    setThreads(next);
    await storage.save(THREAD_INDEX_KEY, next);
    if (id === threadId) newThread();
  }

  async function handleEnv(name: string, value: string): Promise<void> {
    const r = await apiRequest<{ masked?: Record<string, string>; redeploy?: { ok: boolean; detail: string } | null }>('/api/settings', {
      method: 'POST',
      body: { vars: { [name]: value }, redeploy: true },
    });
    if (!r.ok) {
      pushNotice('Could not save ' + name + ': ' + r.message);
      return;
    }
    const masked = r.data?.masked?.[name] ?? '********';
    const dep = r.data?.redeploy;
    pushNotice('Saved ' + name + ' = ' + masked + ' to Vercel. ' + (dep ? (dep.ok ? 'Redeploy started (about a minute).' : 'Redeploy failed: ' + dep.detail) : 'Redeploy to activate.'));
  }

  async function submit(): Promise<void> {
    const raw = input.trim();
    if ((!raw && !attachment) || busy) return;

    const env = raw.match(/^\/env\s+([A-Za-z_][A-Za-z0-9_]*)=([\s\S]+)$/);
    if (env) {
      setInput('');
      await handleEnv(env[1].toUpperCase(), env[2].trim());
      return;
    }
    if (raw === '/memory') {
      setInput('');
      pushNotice(facts.length ? 'Memory: ' + facts.map((f) => f.fact).join(' | ') : 'Memory is empty.');
      return;
    }
    if (raw === '/clear') {
      setInput('');
      newThread();
      return;
    }

    stateRef.current.nodeIndex = 0;
    clearError();
    const text = raw || 'Please describe and analyze this image.';
    const files = attachment ? [{ type: 'file' as const, mediaType: attachment.mediaType, url: attachment.dataUrl }] : undefined;
    setInput('');
    setAttachment(null);
    await sendMessage(files ? { text, files } : { text });
  }

  async function onPickImage(file: File | undefined): Promise<void> {
    if (!file) return;
    setAttachError('');
    try {
      const c = await compressImage(file);
      setAttachment({ dataUrl: c.dataUrl, mediaType: c.mediaType, bytes: c.bytes });
    } catch (e) {
      setAttachError(e instanceof Error ? e.message : 'Could not use that image.');
    }
  }

  function retryWithNextModel(): void {
    stateRef.current.nodeIndex += 1;
    clearError();
    void regenerate();
  }

  const slashHints = useMemo(() => {
    if (!input.startsWith('/') || input.includes(' ')) return [];
    const all = [...SKILLS.map((s) => ({ command: s.command, hint: s.hint })), ...CLIENT_COMMANDS];
    return all.filter((c) => c.command.startsWith(input.toLowerCase())).slice(0, 6);
  }, [input]);

  /* ---------- render ---------- */
  if (authed === null) {
    return <main className='flex min-h-screen items-center justify-center text-sm text-[color:var(--muted)]'>Loading...</main>;
  }

  if (!authed) {
    return (
      <main className='flex min-h-screen items-center justify-center p-4'>
        <form
          className='glass-strong w-full max-w-sm space-y-4 rounded-2xl p-6'
          onSubmit={(e) => {
            e.preventDefault();
            void login();
          }}
        >
          <div className='flex items-center gap-2'>
            <span className='flex h-9 w-9 items-center justify-center rounded-xl' style={{ background: 'rgba(139,108,255,0.2)', border: '1px solid rgba(139,108,255,0.5)' }}>
              <Icon name='lock' size={16} />
            </span>
            <div>
              <h1 className='text-base font-semibold'>Hybrid AI Agent</h1>
              <p className='text-xs text-[color:var(--muted)]'>Enter your app password to continue.</p>
            </div>
          </div>
          <input className='field' type='password' autoFocus autoComplete='current-password' placeholder='App password' value={password} onChange={(e) => setPassword(e.target.value)} />
          {loginError && <p className='text-xs text-red-300' role='alert'>{loginError}</p>}
          <button type='submit' className='neon-btn w-full rounded-xl px-4 py-2.5 text-sm' disabled={loggingIn || password.length === 0}>
            {loggingIn ? 'Checking...' : 'Sign in'}
          </button>
        </form>
      </main>
    );
  }

  const lastAssistantIndex = (() => {
    for (let i = messages.length - 1; i >= 0; i--) if (messages[i].role === 'assistant') return i;
    return -1;
  })();

  return (
    <div className='flex h-screen flex-col'>
      <header className='flex flex-wrap items-center gap-2 px-3 py-2.5 sm:px-4' style={{ borderBottom: '1px solid var(--line)' }}>
        <button type='button' className='ghost-btn rounded-lg p-2 md:hidden' onClick={() => setSidebarOpen(!sidebarOpen)} aria-label='Toggle chats'>
          <Icon name='menu' size={16} />
        </button>
        <div className='mr-auto flex items-center gap-2'>
          <Icon name='spark' size={18} className='text-[color:var(--neon)]' />
          <h1 className='text-sm font-semibold sm:text-base'>Hybrid AI Agent</h1>
          {nodeLabel && <span className='hidden rounded-full px-2.5 py-0.5 text-[11px] text-[color:var(--neon-2)] sm:inline' style={{ border: '1px solid rgba(34,211,238,0.35)', background: 'rgba(34,211,238,0.08)' }}>{nodeLabel}</span>}
        </div>
        <StoragePill />
        <select className='field !w-auto !py-1.5 text-xs' value={persona} onChange={(e) => updatePersona(normalizePersona(e.target.value))} aria-label='Persona'>
          {(Object.keys(PERSONAS) as Persona[]).map((p) => (
            <option key={p} value={p}>
              {PERSONAS[p].label}
            </option>
          ))}
        </select>
        <button type='button' className='neon-btn inline-flex items-center gap-1.5 rounded-lg px-3 py-1.5 text-xs' onClick={() => { setDrawerNotice(null); setConnectorsOpen(true); }}>
          <Icon name='plug' size={13} />
          Connectors
        </button>
        <button type='button' className='ghost-btn rounded-lg px-3 py-1.5 text-xs' onClick={() => void logout()}>
          Sign out
        </button>
      </header>
      <StorageBanner onOpenConnectors={() => setConnectorsOpen(true)} />

      <div className='flex min-h-0 flex-1'>
        <aside className={(sidebarOpen ? 'flex' : 'hidden') + ' w-64 shrink-0 flex-col gap-3 overflow-y-auto p-3 md:flex scroll-thin'} style={{ borderRight: '1px solid var(--line)' }}>
          <button type='button' className='neon-btn inline-flex items-center justify-center gap-1.5 rounded-xl px-3 py-2 text-xs' onClick={newThread}>
            <Icon name='plus' size={13} />
            New chat
          </button>
          <div>
            <p className='mb-1.5 text-[11px] text-[color:var(--muted)]'>Chats</p>
            <ul className='space-y-1'>
              {threads.length === 0 && <li className='text-xs text-[color:var(--muted)]'>No saved chats yet.</li>}
              {threads.map((t) => (
                <li key={t.id} className={'group flex items-center gap-1 rounded-lg px-2 py-1.5 text-xs ' + (t.id === threadId ? 'bg-white/10' : 'hover:bg-white/5')}>
                  <button type='button' className='min-w-0 flex-1 truncate text-left' onClick={() => void openThread(t.id)}>
                    {t.title}
                  </button>
                  <button type='button' className='opacity-0 transition group-hover:opacity-100' onClick={() => void removeThread(t.id)} aria-label='Delete chat'>
                    <Icon name='trash' size={12} />
                  </button>
                </li>
              ))}
            </ul>
          </div>
          <div>
            <p className='mb-1.5 text-[11px] text-[color:var(--muted)]'>Memory</p>
            <ul className='space-y-1'>
              {facts.length === 0 && <li className='text-xs text-[color:var(--muted)]'>The agent saves durable preferences here.</li>}
              {facts.slice(0, 12).map((f) => (
                <li key={f.id} className='group flex items-start gap-1 rounded-lg px-2 py-1.5 text-xs hover:bg-white/5'>
                  <span className='min-w-0 flex-1'>{f.fact}</span>
                  <button type='button' className='opacity-0 transition group-hover:opacity-100' onClick={() => void deleteFact(f.id).then(setFacts)} aria-label='Forget this fact'>
                    <Icon name='x' size={12} />
                  </button>
                </li>
              ))}
            </ul>
          </div>
        </aside>

        <main className='flex min-w-0 flex-1 flex-col'>
          <div className='scroll-thin flex-1 space-y-4 overflow-y-auto px-3 py-4 sm:px-6'>
            {messages.length === 0 && (
              <div className='mx-auto mt-12 max-w-xl text-center'>
                <h2 className='text-xl font-semibold'>What should we build or fix?</h2>
                <p className='mt-2 text-sm text-[color:var(--muted)]'>
                  I can research the web, write code with a separate coder model, read and improve this repo, and check Vercel builds. Try <code>/build</code>, <code>/fix</code> or <code>/research</code>.
                </p>
              </div>
            )}
            {messages.map((m) => (
              <MessageView key={m.id} message={m} onDecision={(id, approved) => void addToolApprovalResponse({ id, approved })} />
            ))}
            {status === 'submitted' && <p className='text-xs text-[color:var(--muted)]'>Thinking...</p>}
            {notices.map((n) => (
              <p key={n.id} className='mx-auto max-w-2xl rounded-xl px-3 py-2 text-xs' style={{ border: '1px solid var(--line)', background: 'rgba(255,255,255,0.04)' }} role='status'>
                {n.text}
              </p>
            ))}
            {error && (
              <div className='mx-auto flex max-w-2xl items-start gap-3 rounded-xl px-3 py-2 text-sm text-red-200' style={{ border: '1px solid rgba(248,113,113,0.4)', background: 'rgba(248,113,113,0.08)' }} role='alert'>
                <span className='flex-1'>{friendlyError(error.message)}</span>
                <button type='button' className='ghost-btn inline-flex items-center gap-1 rounded-lg px-2.5 py-1 text-xs' onClick={retryWithNextModel}>
                  <Icon name='refresh' size={12} />
                  Retry with next model
                </button>
              </div>
            )}
            {!busy && !error && lastAssistantIndex === messages.length - 1 && messages.length > 0 && (
              <div className='flex justify-start'>
                <button type='button' className='ghost-btn inline-flex items-center gap-1 rounded-lg px-2.5 py-1 text-xs' onClick={retryWithNextModel}>
                  <Icon name='refresh' size={12} />
                  Try another model
                </button>
              </div>
            )}
            <div ref={bottomRef} />
          </div>

          <form
            className='px-3 pb-3 sm:px-6'
            onSubmit={(e) => {
              e.preventDefault();
              void submit();
            }}
          >
            {slashHints.length > 0 && (
              <ul className='glass mb-2 rounded-xl p-1 text-xs'>
                {slashHints.map((h) => (
                  <li key={h.command}>
                    <button type='button' className='flex w-full items-center justify-between gap-3 rounded-lg px-2.5 py-1.5 text-left hover:bg-white/10' onClick={() => setInput(h.command.split(' ')[0] + ' ')}>
                      <code>{h.command}</code>
                      <span className='text-[color:var(--muted)]'>{h.hint}</span>
                    </button>
                  </li>
                ))}
              </ul>
            )}
            {attachment && (
              <div className='mb-2 inline-flex items-center gap-2 rounded-lg px-2 py-1 text-xs' style={{ border: '1px solid var(--line)' }}>
                {/* eslint-disable-next-line @next/next/no-img-element */}
                <img src={attachment.dataUrl} alt='Attachment preview' className='h-8 w-8 rounded object-cover' />
                {Math.round(attachment.bytes / 1024)} KB WebP
                <button type='button' onClick={() => setAttachment(null)} aria-label='Remove attachment'>
                  <Icon name='x' size={12} />
                </button>
              </div>
            )}
            {attachError && <p className='mb-2 text-xs text-red-300'>{attachError}</p>}
            <div className='glass flex items-end gap-2 rounded-2xl p-2'>
              <input ref={fileInput} type='file' accept='image/*' className='hidden' onChange={(e) => { void onPickImage(e.target.files?.[0]); e.target.value = ''; }} />
              <button type='button' className='ghost-btn rounded-xl p-2.5' onClick={() => fileInput.current?.click()} aria-label='Attach screenshot'>
                <Icon name='clip' size={16} />
              </button>
              <textarea
                className='max-h-40 min-h-[2.5rem] flex-1 resize-none bg-transparent px-2 py-2 text-sm outline-none'
                rows={1}
                placeholder='Message the agent... (type / for commands, /env NAME=value to set a secret safely)'
                value={input}
                onChange={(e) => setInput(e.target.value)}
                onKeyDown={(e) => {
                  if (e.key === 'Enter' && !e.shiftKey) {
                    e.preventDefault();
                    void submit();
                  }
                }}
              />
              {busy ? (
                <button type='button' className='ghost-btn rounded-xl px-3.5 py-2.5 text-xs' onClick={() => stop()}>
                  Stop
                </button>
              ) : (
                <button type='submit' className='neon-btn rounded-xl p-2.5' disabled={!input.trim() && !attachment} aria-label='Send'>
                  <Icon name='send' size={16} />
                </button>
              )}
            </div>
          </form>
        </main>
      </div>

      <ConnectorsDrawer open={connectorsOpen} onClose={() => setConnectorsOpen(false)} permissions={permissions} onPermissionsChange={updatePermissions} initialNotice={drawerNotice} />
    </div>
  );
}
